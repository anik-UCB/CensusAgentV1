    f.STATE AS STATE_NAME, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS,
    SUM(e.TOTAL_POP_25_PLUS) AS TOTAL_POP_25_PLUS,
    SUM(e.LESS_THAN_HIGH_SCHOOL) AS LESS_THAN_HIGH_SCHOOL,
    SUM(e.HIGH_SCHOOL_OR_GED) AS HIGH_SCHOOL_OR_GED,
    SUM(e.SOME_COLLEGE) AS SOME_COLLEGE,
    SUM(e.ASSOCIATES_DEGREE) AS ASSOCIATES_DEGREE,
    SUM(e.BACHELORS_DEGREE) AS BACHELORS_DEGREE,
    SUM(e.MASTERS_DEGREE) AS MASTERS_DEGREE,
    SUM(e.PROFESSIONAL_OR_DOCTORATE) AS PROFESSIONAL_OR_DOCTORATE
FROM edu e
JOIN fips f ON e.STATE_FIPS = f.STATE_FIPS AND e.COUNTY_FIPS = f.COUNTY_FIPS
GROUP BY f.STATE, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS;

------------------------------------------------------------
-- V_EMPLOYMENT: Labor force by state and county
------------------------------------------------------------
CREATE OR REPLACE VIEW V_EMPLOYMENT AS
WITH fips AS (
    SELECT DISTINCT STATE, STATE_FIPS, COUNTY_FIPS, COUNTY
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_METADATA_CBG_FIPS_CODES"
    WHERE STATE IS NOT NULL
),
emp AS (
    SELECT
        LEFT(CENSUS_BLOCK_GROUP, 2) AS STATE_FIPS,
        SUBSTR(CENSUS_BLOCK_GROUP, 3, 3) AS COUNTY_FIPS,
        "B23025e1" AS POP_16_PLUS,
        "B23025e2" AS IN_LABOR_FORCE,
        "B23025e4" AS EMPLOYED,
        "B23025e5" AS UNEMPLOYED,
        "B23025e6" AS ARMED_FORCES,
        "B23025e7" AS NOT_IN_LABOR_FORCE
    FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_CBG_B23"
)
SELECT
    f.STATE AS STATE_NAME, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS,
    SUM(e.POP_16_PLUS) AS POP_16_PLUS,
    SUM(e.IN_LABOR_FORCE) AS IN_LABOR_FORCE,
    SUM(e.EMPLOYED) AS EMPLOYED,
    SUM(e.UNEMPLOYED) AS UNEMPLOYED,
    SUM(e.ARMED_FORCES) AS ARMED_FORCES,
    SUM(e.NOT_IN_LABOR_FORCE) AS NOT_IN_LABOR_FORCE,
    ROUND(SUM(e.UNEMPLOYED) * 100.0 / NULLIF(SUM(e.IN_LABOR_FORCE), 0), 2) AS UNEMPLOYMENT_RATE,
    ROUND(SUM(e.IN_LABOR_FORCE) * 100.0 / NULLIF(SUM(e.POP_16_PLUS), 0), 2) AS LABOR_FORCE_PARTICIPATION_RATE
FROM emp e
JOIN fips f ON e.STATE_FIPS = f.STATE_FIPS AND e.COUNTY_FIPS = f.COUNTY_FIPS
GROUP BY f.STATE, f.STATE_FIPS, f.COUNTY, f.COUNTY_FIPS;

------------------------------------------------------------
-- V_STATE_SUMMARY: Quick state-level population rollup
------------------------------------------------------------
CREATE OR REPLACE VIEW V_STATE_SUMMARY AS
SELECT
    STATE_NAME, STATE_FIPS,
    SUM(TOTAL_POPULATION) AS TOTAL_POPULATION,
    SUM(MALE_POPULATION) AS MALE_POPULATION,
    SUM(FEMALE_POPULATION) AS FEMALE_POPULATION,
    SUM(POP_UNDER_18) AS POP_UNDER_18,
    SUM(POP_18_TO_34) AS POP_18_TO_34,
    SUM(POP_35_TO_54) AS POP_35_TO_54,
    SUM(POP_55_TO_69) AS POP_55_TO_69,
    SUM(POP_70_PLUS) AS POP_70_PLUS,
    SUM(WHITE_NON_HISPANIC) AS WHITE_NON_HISPANIC,
    SUM(BLACK_NON_HISPANIC) AS BLACK_NON_HISPANIC,
    SUM(ASIAN_NON_HISPANIC) AS ASIAN_NON_HISPANIC,
    SUM(HISPANIC_LATINO) AS HISPANIC_LATINO
FROM V_POPULATION
GROUP BY STATE_NAME, STATE_FIPS;

------------------------------------------------------------
-- V_STATE_INCOME: State-level income summary (one row per state)
------------------------------------------------------------
CREATE OR REPLACE VIEW V_STATE_INCOME AS
SELECT
    STATE_NAME,
    STATE_FIPS,
    SUM(TOTAL_HOUSEHOLDS) AS TOTAL_HOUSEHOLDS,
    SUM(HH_UNDER_10K) AS HH_UNDER_10K,
    SUM(HH_10K_TO_24K) AS HH_10K_TO_24K,
    SUM(HH_25K_TO_49K) AS HH_25K_TO_49K,
    SUM(HH_50K_TO_99K) AS HH_50K_TO_99K,
    SUM(HH_100K_TO_199K) AS HH_100K_TO_199K,
    SUM(HH_200K_PLUS) AS HH_200K_PLUS,
    ROUND(AVG(NULLIF(AVG_MEDIAN_HOUSEHOLD_INCOME, 0)), 0) AS MEDIAN_HOUSEHOLD_INCOME,
    ROUND(AVG(NULLIF(AVG_PER_CAPITA_INCOME, 0)), 0) AS PER_CAPITA_INCOME
FROM V_INCOME
GROUP BY STATE_NAME, STATE_FIPS;

------------------------------------------------------------
-- V_STATE_EMPLOYMENT: State-level employment summary (one row per state)
------------------------------------------------------------
CREATE OR REPLACE VIEW V_STATE_EMPLOYMENT AS
SELECT
    STATE_NAME,
    STATE_FIPS,
    SUM(POP_16_PLUS) AS POP_16_PLUS,
    SUM(IN_LABOR_FORCE) AS IN_LABOR_FORCE,
    SUM(EMPLOYED) AS EMPLOYED,
    SUM(UNEMPLOYED) AS UNEMPLOYED,
    SUM(ARMED_FORCES) AS ARMED_FORCES,
    SUM(NOT_IN_LABOR_FORCE) AS NOT_IN_LABOR_FORCE,
    ROUND(SUM(UNEMPLOYED) * 100.0 / NULLIF(SUM(IN_LABOR_FORCE), 0), 2) AS UNEMPLOYMENT_RATE,
    ROUND(SUM(IN_LABOR_FORCE) * 100.0 / NULLIF(SUM(POP_16_PLUS), 0), 2) AS LABOR_FORCE_PARTICIPATION_RATE
FROM V_EMPLOYMENT
GROUP BY STATE_NAME, STATE_FIPS;

------------------------------------------------------------
-- V_STATE_EDUCATION: State-level education summary (one row per state)
------------------------------------------------------------
CREATE OR REPLACE VIEW V_STATE_EDUCATION AS
SELECT
    STATE_NAME,
    STATE_FIPS,
    SUM(TOTAL_POP_25_PLUS) AS TOTAL_POP_25_PLUS,
    SUM(LESS_THAN_HIGH_SCHOOL) AS LESS_THAN_HIGH_SCHOOL,
    SUM(HIGH_SCHOOL_OR_GED) AS HIGH_SCHOOL_OR_GED,
    SUM(SOME_COLLEGE) AS SOME_COLLEGE,
    SUM(ASSOCIATES_DEGREE) AS ASSOCIATES_DEGREE,
    SUM(BACHELORS_DEGREE) AS BACHELORS_DEGREE,
    SUM(MASTERS_DEGREE) AS MASTERS_DEGREE,
    SUM(PROFESSIONAL_OR_DOCTORATE) AS PROFESSIONAL_OR_DOCTORATE,
    ROUND(SUM(BACHELORS_DEGREE) * 100.0 / NULLIF(SUM(TOTAL_POP_25_PLUS), 0), 1) AS PCT_BACHELORS,
    ROUND((SUM(BACHELORS_DEGREE) + SUM(MASTERS_DEGREE) + SUM(PROFESSIONAL_OR_DOCTORATE)) * 100.0 / NULLIF(SUM(TOTAL_POP_25_PLUS), 0), 1) AS PCT_COLLEGE_OR_HIGHER
FROM V_EDUCATION
GROUP BY STATE_NAME, STATE_FIPS;

------------------------------------------------------------
-- V_STATE_HOUSING: State-level housing summary (one row per state)
------------------------------------------------------------
CREATE OR REPLACE VIEW V_STATE_HOUSING AS
SELECT
    STATE_NAME,
    STATE_FIPS,
    SUM(TOTAL_HOUSING_UNITS) AS TOTAL_HOUSING_UNITS,
    SUM(OWNER_OCCUPIED_UNITS) AS OWNER_OCCUPIED_UNITS,
    SUM(RENTER_OCCUPIED_UNITS) AS RENTER_OCCUPIED_UNITS,
    ROUND(SUM(OWNER_OCCUPIED_UNITS) * 100.0 / NULLIF(SUM(OWNER_OCCUPIED_UNITS) + SUM(RENTER_OCCUPIED_UNITS), 0), 1) AS HOMEOWNERSHIP_RATE,
    ROUND(AVG(NULLIF(AVG_MEDIAN_HOME_VALUE, 0)), 0) AS MEDIAN_HOME_VALUE
FROM V_HOUSING
GROUP BY STATE_NAME, STATE_FIPS;
